export function findMatchingRegulations(query: string): Citation[] {
  const q = query.toLowerCase();
  const matched = APPROVED_REGULATIONS.filter((reg) => {
    if (q.includes("transfer pricing") || q.includes("tp doc") || q.includes("pmk 172") || q.includes("afiliasi") || q.includes("arm's length")) {
      return reg.id.startsWith("pmk-172");
    }
    if (q.includes("sp2dk") || q.includes("pemeriksaan") || q.includes("audit") || q.includes("djp notice") || q.includes("14 hari")) {
      return reg.id === "uu-kup-art14-sp2dk";
    }
    if (q.includes("p3b") || q.includes("treaty") || q.includes("dgt") || q.includes("cross border") || q.includes("wpln") || q.includes("pp 28")) {
      return reg.id === "per-25-pj-2018-dgt" || reg.id === "pp-28-2025-art12";
    }
    if (q.includes("dividen") || q.includes("cit") || q.includes("pph badan") || q.includes("hpp") || q.includes("22%")) {
      return reg.id === "uu-hpp-cit-art31a" || reg.id === "pmk-18-2021-deductions";
    }
    return false;
  });

  return matched.length > 0 ? matched : [APPROVED_REGULATIONS[0], APPROVED_REGULATIONS[2]];
}
